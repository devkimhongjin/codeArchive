-- AI code review (#251). The feature is off unless an operator enables it;
-- these tables stay empty until then.
CREATE TABLE ai_consents (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    notice_version VARCHAR(40) NOT NULL,
    granted_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE ai_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    solution_id BIGINT NOT NULL REFERENCES solutions(id) ON DELETE CASCADE,
    cache_key VARCHAR(64) NOT NULL,
    provider VARCHAR(40) NOT NULL,
    model VARCHAR(100) NOT NULL,
    prompt_version VARCHAR(40) NOT NULL,
    summary VARCHAR(2000) NOT NULL,
    suggestions TEXT NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_ai_reviews_user_cache UNIQUE (user_id, cache_key)
);
CREATE INDEX idx_ai_reviews_solution ON ai_reviews(solution_id);

CREATE TABLE ai_daily_usage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    usage_date DATE NOT NULL,
    request_count INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uk_ai_daily_usage_user_date UNIQUE (user_id, usage_date)
);
